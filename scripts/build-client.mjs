// 产出 lib/client.js：client 半区源文件本身就是 DSH 客户端模块表格式
// （window.__ModuleLoader__.load，官方模板同款），构建只做拷贝 + 版本横幅，
// 不引入额外打包链。package.json 的 dsh.client 声明与 exports["./client"] 指向该产物。
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const src = readFileSync(resolve(root, "src", "client.js"), "utf8");
if (!src.includes("window.__ModuleLoader__.load")) {
  throw new Error("build-client: src/client.js 缺少 window.__ModuleLoader__.load 注册形态");
}
const banner = `/* ${pkg.name} client half v${pkg.version} — generated by scripts/build-client.mjs, do not edit */\n`;
mkdirSync(resolve(root, "lib"), { recursive: true });
writeFileSync(resolve(root, "lib", "client.js"), banner + src, "utf8");
console.log(`build-client: lib/client.js written (${src.length} bytes)`);
